/** Unites du catalogue, affichees apres le prix. */
const UNITS_AR: Record<string, string> = {
  kg: "كلغ",
  lot: "حزمة",
  piece: "حبة",
  pièce: "حبة",
  botte: "حزمة",
  g: "غ",
}

export function interpolate(text: string, vars?: TranslationVars): string {
  if (!vars) return text
  return text.replace(/\{(\w+)\}/g, (match, key: string) => (key in vars ? String(vars[key]) : match))
}

/** Traduit une phrase francaise ; sans traduction arabe, le francais reste affiche. */
export function translate(locale: Locale, french: string, vars?: TranslationVars): string {
  return interpolate(locale === "ar" ? ARABIC[french] ?? french : french, vars)
}

export function translateUnit(locale: Locale, unit: string): string {
  return locale === "ar" ? UNITS_AR[unit.trim().toLowerCase()] ?? unit : unit
}
