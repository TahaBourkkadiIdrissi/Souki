const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
fs.mkdirSync('outputs/ia-app-ref', {recursive:true});
const knowledge = fs.readFileSync('back-end/data/souki-assistant-connaissances.md', 'utf8');
const questions = ['Comment ça marche ?', 'Horaires de livraison', 'Frais de livraison', 'Moyens de paiement', "C'est quoi le panier malin ?"];
const suggestions = questions.map(question => ({question,answer:knowledge.split(`## ${question}\n`)[1].split('\n## ')[0].trim()}));
(async () => {
  const browser = await chromium.launch({ headless: true });
  const bypassCSP = process.env.SOUKI_QA_DEV === '1'; // Webpack development bundles require eval; production does not.
  const context = await browser.newContext({viewport:{width:375,height:812}, reducedMotion:'reduce', bypassCSP});
  await context.addInitScript(() => {
    localStorage.setItem('souki-chat-hint', 'seen');
    sessionStorage.setItem('souki-launched', '1');
    Object.defineProperty(navigator,'standalone',{value:true});
  });
  await context.route('**/backend/**', route => {
    const url = route.request().url();
    let body = [];
    if(url.includes('/auth/me')) body={id:1,role:'CLIENT',roles:['CLIENT'],permissions:['client.dashboard.access'],is_verified:true,is_active:true,onboarding_completed:true};
    if(url.includes('/user/profile')) body={prenom:'Amina',nom:'',address:{adresse:'Saïss',ville:'Fès'},email_verified:true};
    if(url.includes('/assistant/suggestions')) body=suggestions;
    if(url.includes('/assistant/chat')) return route.fulfill({status:503,json:{detail:'Assistante momentanément indisponible. Les questions rapides restent accessibles.'}});
    return route.fulfill({json:body});
  });
  await context.route('https://**', route => route.abort());
  const page = await context.newPage();
  const pageErrors = [];
  page.on('pageerror',error=>pageErrors.push(error.message));
  await page.goto('http://127.0.0.1:3000/pwa-welcome?preview=pwa', {waitUntil:'domcontentloaded',timeout:90000});
  await page.getByRole('link',{name:'Adresse de livraison : Saïss, Fès'}).waitFor();
  await page.addStyleTag({content:'nextjs-portal { display:none !important }'});
  await page.evaluate(async () => {
    await document.fonts.ready;
    await Promise.all([...document.images].filter(img=>img.src.includes('/brand/') || img.src.includes('/_next/image')).map(img=>img.decode().catch(()=>{})));
  });
  const dismiss=page.getByRole('button',{name:"Masquer l'installation"});
  if(await dismiss.isVisible()) await dismiss.click();
  for(const width of [320,375,430]) {
    await page.setViewportSize({width,height:812});
    await page.screenshot({path:`outputs/ia-app-ref/home-${width}.png`});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  }
  await page.setViewportSize({width:375,height:812});
  if(process.env.SOUKI_CAPTURE_MANIFEST === '1') await page.screenshot({path:'apps/client/public/screenshots/home-narrow.png'});
  await page.setViewportSize({width:1280,height:800});
  if(process.env.SOUKI_CAPTURE_MANIFEST === '1') await page.screenshot({path:'apps/client/public/screenshots/home-wide.png'});
  await page.setViewportSize({width:375,height:812});
  await page.evaluate(()=>window.scrollTo(0,600));
  await page.waitForTimeout(300);
  await page.screenshot({path:'outputs/ia-app-ref/header-scrolled.png'});
  const visible = await page.getByRole('link',{name:'Adresse de livraison : Saïss, Fès'}).evaluateAll(nodes=>nodes.some(n=>{const r=n.getBoundingClientRect();return r.top>=0&&r.bottom<100}));
  assert.equal(visible,true);
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.getByRole('button',{name:'Discuter avec Souki'}).click();
  await page.getByRole('button',{name:'Frais de livraison',exact:true}).click();
  await page.getByRole('log').getByText(/La livraison coûte 15 DH/).waitFor();
  await page.screenshot({path:'outputs/ia-app-ref/chat.png'});
  await page.getByRole('textbox',{name:'Votre message à Souki'}).fill('Bonjour');
  await page.getByRole('button',{name:'Envoyer',exact:true}).click();
  await page.getByRole('alert').getByText(/indisponible/).waitFor();
  await page.route('**/api/assistant/chat', route => route.fulfill({contentType:'text/event-stream',body:'data: {"delta":"مرحبا **Souki**"}\n\ndata: {"delta":"\\n- Tomates : 8 DH/kg"}\n\ndata: {"done":true}\n\n'}));
  await page.getByRole('button',{name:'Envoyer',exact:true}).click();
  await page.getByRole('log').getByText('• Tomates : 8 DH/kg').waitFor();
  assert.equal(await page.getByRole('log').locator('strong').innerText(),'Souki');
  await page.setViewportSize({width:375,height:500});
  await page.waitForTimeout(200);
  assert.equal(await page.getByRole('textbox',{name:'Votre message à Souki'}).evaluate(el=>el.getBoundingClientRect().bottom<=innerHeight),true);
  await page.setViewportSize({width:375,height:812});
  await page.getByRole('button',{name:'Nouvelle conversation'}).click();
  assert.equal(await page.getByRole('log').getByText(/La livraison coûte 15 DH/).count(),0);
  await page.getByRole('button',{name:'Fermer',exact:true}).click();
  const ios = await browser.newContext({viewport:{width:375,height:812},bypassCSP,userAgent:'Mozilla/5.0 (iPhone; CPU iPhone OS 26_0 like Mac OS X) AppleWebKit/605.1.15 Version/26.0 Mobile/15E148 Safari/604.1'});
  await ios.route('**/backend/**',r=>r.fulfill({status:401,json:{detail:'anonymous'}}));
  await ios.route('https://**',r=>r.abort());
  const iphone = await ios.newPage();
  await iphone.goto('http://127.0.0.1:3000/faq',{waitUntil:'domcontentloaded'});
  await iphone.getByRole('button',{name:'Télécharger l’application'}).or(iphone.getByRole('button',{name:"Télécharger l'application"})).click();
  await iphone.getByRole('dialog').waitFor();
  await iphone.screenshot({path:'outputs/ia-app-ref/ios-install.png'});
  await iphone.getByRole('button',{name:'Fermer le guide'}).click();
  const desktop = await browser.newContext({viewport:{width:1280,height:800},bypassCSP});
  await desktop.route('**/backend/**',r=>r.fulfill({status:401,json:{detail:'anonymous'}}));
  await desktop.route('https://**',r=>r.abort());
  await desktop.addInitScript(()=>document.addEventListener('DOMContentLoaded',()=>{
    const event = new Event('beforeinstallprompt',{cancelable:true});
    event.prompt = async()=>{window.__prompted=true};
    event.userChoice=Promise.resolve({outcome:'accepted'});
    window.dispatchEvent(event);
  }));
  const desktopPage = await desktop.newPage();
  await desktopPage.goto('http://127.0.0.1:3000/faq',{waitUntil:'domcontentloaded'});
  await desktopPage.getByRole('button',{name:"Télécharger l'application"}).click();
  assert.equal(await desktopPage.evaluate(()=>window.__prompted),true);
  assert.equal(await desktopPage.evaluate(()=>window.soukiInstallPrompt),null);
  assert.deepEqual(pageErrors,[]);
  await browser.close();
  console.log('Verified header widths/scroll, chat quick answers, 503 recovery, streamed Unicode and bold/list formatting, keyboard-sized viewport, reset, iOS guide, desktop install event.');
})().catch(e=>{console.error(e);process.exit(1)});
